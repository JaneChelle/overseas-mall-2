import { expect, test } from '@playwright/test'

test('catalog search, categories, combined filters, sorting, and no-results recovery', async ({ page }) => {
  await page.goto('/')
  const cards = page.locator('.product-card')
  const search = page.getByRole('searchbox', { name: 'Search products' })
  await expect(cards).toHaveCount(12)
  await search.fill('lamp')
  await expect(cards).toHaveCount(1)
  await expect(cards.first()).toContainText('Arc table lamp')
  await page.getByRole('button', { name: 'Clear search', exact: true }).click()
  await page.locator('[data-test-id="category-radio-tech"]').click()
  await expect(cards).toHaveCount(2)
  await search.fill('nonexistent-product')
  await expect(page.getByRole('heading', { name: 'No finds this time.' })).toBeVisible()
  await page.getByRole('button', { name: 'Explore all products' }).click()
  await expect(cards).toHaveCount(12)
  await page.getByRole('button', { name: 'Filters', exact: true }).click()
  await page.getByLabel('In stock only').check()
  await expect(cards).toHaveCount(11)
  await page.getByLabel('Collection', { exact: true }).selectOption('new')
  await expect(cards).toHaveCount(4)
  await page.getByLabel('Sort by:').selectOption('price-low')
  await expect(cards.first()).toContainText('A little daily journal')
  await page.getByRole('button', { name: 'Reset filters' }).click()
  await page.getByLabel('Sort by:').selectOption('featured')
  await expect(cards).toHaveCount(12)
})

test('card color survives details; quantity, merged variants, persistence, checkout, and removal work', async ({ page }) => {
  const runtimeErrors: string[] = []
  page.on('pageerror', error => runtimeErrors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: 'Forest Arc table lamp', exact: true }).click()
  await page.getByRole('button', { name: 'View Arc table lamp', exact: true }).click()
  let detail = page.getByRole('dialog', { name: 'Arc table lamp' })
  await expect(detail.getByRole('button', { name: 'Select Forest' })).toHaveAttribute('aria-pressed', 'true')
  await page.keyboard.press('Escape')
  await expect(detail).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'View Arc table lamp', exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'View Arc table lamp', exact: true }).click()
  detail = page.getByRole('dialog', { name: 'Arc table lamp' })
  await detail.getByRole('button', { name: 'Increase Arc table lamp quantity' }).click()
  await detail.getByRole('button', { name: 'Add to bag', exact: true }).click()
  await expect(detail).toHaveCount(0)
  await page.getByRole('button', { name: 'View bag', exact: true }).click()
  let bag = page.getByRole('dialog', { name: 'Your shopping bag' })
  await expect(bag).toContainText('Forest')
  await expect(bag.locator('.cart-total')).toContainText('$138.00')
  await bag.getByRole('button', { name: 'Close your shopping bag' }).click()
  await page.getByRole('button', { name: 'Add Arc table lamp to bag', exact: true }).click()
  await page.getByRole('button', { name: 'Charcoal Arc table lamp', exact: true }).click()
  await page.getByRole('button', { name: 'Add Arc table lamp to bag', exact: true }).click()
  await page.reload()
  await page.getByRole('button', { name: 'Shopping bag, 4 items' }).click()
  bag = page.getByRole('dialog', { name: 'Your shopping bag' })
  await expect(bag.locator('.cart-line')).toHaveCount(2)
  await expect(bag.getByLabel('Arc table lamp Forest quantity', { exact: true })).toHaveText('3')
  await expect(bag.locator('.cart-total')).toContainText('$276.00')
  await bag.getByRole('button', { name: 'Decrease Arc table lamp Forest quantity' }).click()
  await expect(bag.locator('.cart-total')).toContainText('$207.00')
  await bag.getByRole('button', { name: 'Continue to checkout' }).click()
  const checkout = page.getByRole('dialog', { name: 'Checkout preview' })
  await expect(checkout).toContainText('No payment will be taken')
  await expect(checkout).toContainText('$207.00')
  await checkout.getByRole('button', { name: 'Back to your bag' }).click()
  bag = page.getByRole('dialog', { name: 'Your shopping bag' })
  await bag.getByRole('button', { name: 'Remove Arc table lamp Forest from bag' }).click()
  await bag.getByRole('button', { name: 'Remove Arc table lamp Charcoal from bag' }).click()
  await expect(bag).toContainText('Your bag is empty')
  await bag.getByRole('button', { name: 'Explore the collection' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  expect(runtimeErrors).toEqual([])
})

test('wishlist persists and recovers from damaged storage', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Save Arc table lamp to wishlist' }).click()
  await page.getByRole('button', { name: 'Wishlist, 1 saved products' }).click()
  await expect(page.locator('.product-card')).toHaveCount(1)
  await page.reload()
  await expect(page.getByRole('button', { name: 'Wishlist, 1 saved products' })).toBeVisible()
  await page.getByRole('button', { name: 'Wishlist, 1 saved products' }).click()
  await page.getByRole('button', { name: 'Remove Arc table lamp from wishlist' }).click()
  await expect(page.getByRole('heading', { name: 'Make a little room for favorites.' })).toBeVisible()
  await page.evaluate(() => {
    localStorage.setItem('form-field-cart-v1', '{invalid json')
    localStorage.setItem('form-field-saved-v1', '{invalid json')
  })
  await page.reload()
  await expect(page.getByRole('button', { name: 'Shopping bag, 0 items' })).toBeVisible()
  await expect(page.locator('.product-card')).toHaveCount(12)
})

for (const width of [1440, 768, 390, 375]) {
  test(`layout and image assets at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: width < 500 ? 844 : 1000 })
    await page.goto('/')
    await page.evaluate(async () => {
      document.querySelectorAll('img').forEach(image => { image.loading = 'eager' })
      await Promise.all(Array.from(document.images).map(image => image.decode()))
      await document.fonts.ready
    })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await expect(page.locator('.product-card')).toHaveCount(12)
    await page.screenshot({ path: `artifacts/storefront-${width}.png`, fullPage: true })
    if (width < 500) {
      await page.getByRole('button', { name: 'Open navigation' }).click()
      await page.getByRole('navigation', { name: 'Mobile navigation' }).getByRole('button', { name: 'Tech & accessories' }).click()
      await expect(page.locator('.product-card')).toHaveCount(2)
      await expect(page.getByRole('dialog')).toHaveCount(0)
      await page.getByRole('button', { name: 'View Studio wireless headphones', exact: true }).click()
      const detail = page.getByRole('dialog', { name: 'Studio wireless headphones' })
      await detail.getByRole('button', { name: 'Select Oat' }).click()
      await page.screenshot({ path: `artifacts/product-mobile-${width}.png`, fullPage: false })
      await detail.getByRole('button', { name: 'Add to bag', exact: true }).click()
      await page.getByRole('button', { name: 'View bag', exact: true }).click()
      await expect(page.getByRole('dialog', { name: 'Your shopping bag' })).toContainText('Oat')
      await page.screenshot({ path: `artifacts/cart-mobile-${width}.png`, fullPage: false })
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    }
  })
}
